/**
 * CF-169: Tool Sharing — Generate Shareable Result Links
 * Encode tool output as shareable URLs or downloadable PDF data.
 */
(function () {
  'use strict';

  var SHARE_BASE_PATH = '/shared/';
  var MAX_URL_LENGTH = 2000;

  /**
   * Compress and encode data for URL embedding.
   * Uses base64 encoding of JSON; for large payloads, truncates gracefully.
   * @param {object} data
   * @returns {string}
   */
  function encodeData(data) {
    var json = JSON.stringify(data);
    return btoa(unescape(encodeURIComponent(json)));
  }

  /**
   * Decode URL-embedded data.
   * @param {string} encoded
   * @returns {object|null}
   */
  function decodeData(encoded) {
    try {
      var json = decodeURIComponent(escape(atob(encoded)));
      return JSON.parse(json);
    } catch (_e) {
      return null;
    }
  }

  /**
   * Generate a shareable URL for tool output.
   * @param {{ toolId: string, title: string, result: object }} params
   * @returns {{ url: string, method: "url"|"api", truncated: boolean }}
   */
  function generateShareUrl(params) {
    if (!params || !params.toolId) {
      return { url: '', method: 'url', truncated: false };
    }

    var payload = {
      t: params.toolId,
      n: params.title || '',
      r: params.result || {},
      ts: Date.now()
    };

    var encoded = encodeData(payload);
    var origin = window.location.origin || '';
    var url = origin + SHARE_BASE_PATH + '?d=' + encodeURIComponent(encoded);

    if (url.length <= MAX_URL_LENGTH) {
      return { url: url, method: 'url', truncated: false };
    }

    // Truncate result for URL and flag it
    var minPayload = { t: payload.t, n: payload.n, r: { summary: String(params.result).substring(0, 200) }, ts: payload.ts };
    var minEncoded = encodeData(minPayload);
    return {
      url: origin + SHARE_BASE_PATH + '?d=' + encodeURIComponent(minEncoded),
      method: 'url',
      truncated: true
    };
  }

  /**
   * Parse shared data from the current URL.
   * @returns {object|null}
   */
  function parseShareUrl() {
    var params = new URLSearchParams(window.location.search);
    var d = params.get('d');
    if (!d) return null;
    return decodeData(d);
  }

  /**
   * Generate downloadable PDF data as a Blob URL (simple HTML-to-print approach).
   * @param {{ toolId: string, title: string, result: object, generatedAt: string }} params
   * @returns {{ blobUrl: string, filename: string }}
   */
  function generatePdfData(params) {
    var title = (params && params.title) || 'Tool Result';
    var toolId = (params && params.toolId) || 'unknown';
    var result = (params && params.result) || {};
    var generatedAt = (params && params.generatedAt) || new Date().toLocaleString();

    var html =
      '<!DOCTYPE html><html><head><meta charset="utf-8">' +
      '<title>' + escapeHtml(title) + '</title>' +
      '<style>' +
        'body{font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,sans-serif;max-width:800px;margin:0 auto;padding:40px;color:#111827}' +
        'h1{font-size:22px;border-bottom:2px solid #4F46E5;padding-bottom:8px}' +
        '.meta{color:#6b7280;font-size:13px;margin-bottom:24px}' +
        'pre{background:#f9fafb;border:1px solid #e5e7eb;border-radius:6px;padding:16px;overflow-x:auto;font-size:13px}' +
        'table{width:100%;border-collapse:collapse;margin:16px 0}' +
        'th,td{text-align:left;padding:8px 12px;border-bottom:1px solid #e5e7eb}' +
        'th{background:#f9fafb;font-weight:600}' +
        '@media print{body{padding:20px}}' +
      '</style></head><body>' +
      '<h1>' + escapeHtml(title) + '</h1>' +
      '<div class="meta">Tool: ' + escapeHtml(toolId) + ' &middot; Generated: ' + escapeHtml(generatedAt) + '</div>' +
      renderResultHtml(result) +
      '<div class="meta" style="margin-top:32px;border-top:1px solid #e5e7eb;padding-top:12px">Generated by Cortex Freelancer</div>' +
      '</body></html>';

    var blob = new Blob([html], { type: 'text/html' });
    var blobUrl = URL.createObjectURL(blob);
    var filename = toolId + '-result-' + Date.now() + '.html';

    return { blobUrl: blobUrl, filename: filename };
  }

  /**
   * Render result object as HTML for PDF/print.
   * @param {*} result
   * @returns {string}
   */
  function renderResultHtml(result) {
    if (typeof result === 'string') {
      return '<pre>' + escapeHtml(result) + '</pre>';
    }

    if (Array.isArray(result)) {
      if (result.length === 0) return '<p>No results.</p>';
      if (typeof result[0] === 'object') {
        var keys = Object.keys(result[0]);
        var html = '<table><thead><tr>';
        keys.forEach(function (k) { html += '<th>' + escapeHtml(k) + '</th>'; });
        html += '</tr></thead><tbody>';
        result.forEach(function (row) {
          html += '<tr>';
          keys.forEach(function (k) { html += '<td>' + escapeHtml(String(row[k] != null ? row[k] : '')) + '</td>'; });
          html += '</tr>';
        });
        html += '</tbody></table>';
        return html;
      }
      return '<pre>' + escapeHtml(JSON.stringify(result, null, 2)) + '</pre>';
    }

    if (typeof result === 'object' && result !== null) {
      var html = '<table><tbody>';
      Object.keys(result).forEach(function (key) {
        html += '<tr><td style="font-weight:600">' + escapeHtml(key) + '</td><td>' + escapeHtml(String(result[key] != null ? result[key] : '')) + '</td></tr>';
      });
      html += '</tbody></table>';
      return html;
    }

    return '<pre>' + escapeHtml(String(result)) + '</pre>';
  }

  /**
   * Trigger a download of the generated file.
   * @param {{ blobUrl: string, filename: string }} pdfData
   */
  function download(pdfData) {
    if (!pdfData || !pdfData.blobUrl) return;
    var a = document.createElement('a');
    a.href = pdfData.blobUrl;
    a.download = pdfData.filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
  }

  /**
   * Copy share URL to clipboard.
   * @param {string} url
   * @returns {Promise<boolean>}
   */
  async function copyToClipboard(url) {
    try {
      await navigator.clipboard.writeText(url);
      return true;
    } catch (_err) {
      // Fallback
      var ta = document.createElement('textarea');
      ta.value = url;
      ta.style.position = 'fixed';
      ta.style.opacity = '0';
      document.body.appendChild(ta);
      ta.select();
      var ok = document.execCommand('copy');
      document.body.removeChild(ta);
      return ok;
    }
  }

  function escapeHtml(str) {
    if (!str) return '';
    return String(str).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  }

  // Export to namespace
  window.CortexFreelancer = window.CortexFreelancer || {};
  window.CortexFreelancer.ToolShareLinks = {
    generateShareUrl: generateShareUrl,
    parseShareUrl: parseShareUrl,
    generatePdfData: generatePdfData,
    download: download,
    copyToClipboard: copyToClipboard,
    encodeData: encodeData,
    decodeData: decodeData
  };
})();
