/**
 * CF-084: Inline Style → External CSS Extractor
 *
 * Scans DOM for inline style attributes, generates CSS class equivalents,
 * and produces a tools.css template file content.
 *
 * Usage:
 *   CortexFreelancer.styleExtractor.scan()        — find inline styles
 *   CortexFreelancer.styleExtractor.extract()      — scan + generate CSS classes
 *   CortexFreelancer.styleExtractor.generateCSS()  — get tools.css content
 *   CortexFreelancer.styleExtractor.apply()        — replace inline styles with classes
 */
window.CortexFreelancer = window.CortexFreelancer || {};

(function () {
  'use strict';

  var lastResults = [];
  var generatedClasses = {};
  var classCounter = 0;

  /**
   * Describe an element for reports.
   */
  function describeElement(el) {
    var tag = el.tagName.toLowerCase();
    var id = el.id ? '#' + el.id : '';
    var cls = el.className && typeof el.className === 'string'
      ? '.' + el.className.trim().split(/\s+/).join('.')
      : '';
    return tag + id + cls;
  }

  /**
   * Normalize a style string for dedup (sort properties, trim).
   */
  function normalizeStyle(styleStr) {
    return styleStr
      .split(';')
      .map(function (s) { return s.trim(); })
      .filter(Boolean)
      .sort()
      .join('; ');
  }

  /**
   * Generate a class name from style properties.
   */
  function generateClassName(styleStr) {
    // Try to derive a meaningful name from properties
    var props = styleStr.split(';').map(function (s) { return s.trim().split(':')[0].trim(); }).filter(Boolean);
    var meaningful = props.slice(0, 2).map(function (p) {
      return p.replace(/[^a-zA-Z]/g, '-');
    }).join('-');

    classCounter++;
    return 'cf-util-' + (meaningful || 'style') + '-' + classCounter;
  }

  /**
   * Scan DOM for elements with inline styles.
   * @param {Element} [root=document.body]
   * @returns {Array}
   */
  function scan(root) {
    root = root || document.body;
    if (!root) return [];

    var results = [];
    var allElements = root.querySelectorAll('[style]');

    for (var i = 0; i < allElements.length; i++) {
      var el = allElements[i];
      var styleValue = el.getAttribute('style');
      if (!styleValue || !styleValue.trim()) continue;

      results.push({
        element: el,
        description: describeElement(el),
        inlineStyle: styleValue.trim(),
        normalized: normalizeStyle(styleValue)
      });
    }

    lastResults = results;
    console.log('[StyleExtractor] Found', results.length, 'element(s) with inline styles');
    return results;
  }

  /**
   * Extract inline styles and generate CSS class equivalents.
   * Groups identical styles into the same class.
   * @param {Element} [root]
   * @returns {Object} { classes: {className: cssRule}, results: Array }
   */
  function extract(root) {
    var results = scan(root);
    generatedClasses = {};
    var normalizedMap = {}; // normalized style → className

    for (var i = 0; i < results.length; i++) {
      var entry = results[i];
      var norm = entry.normalized;

      if (normalizedMap[norm]) {
        // Reuse existing class for same style
        entry.suggestedClass = normalizedMap[norm];
      } else {
        var cls = generateClassName(entry.inlineStyle);
        normalizedMap[norm] = cls;
        entry.suggestedClass = cls;

        // Build CSS rule
        var properties = entry.inlineStyle.split(';')
          .map(function (s) { return s.trim(); })
          .filter(Boolean)
          .map(function (s) { return '  ' + s + ';'; })
          .join('\n');

        generatedClasses[cls] = '.' + cls + ' {\n' + properties + '\n}';
      }
    }

    console.log('[StyleExtractor] Generated', Object.keys(generatedClasses).length,
      'unique CSS class(es) for', results.length, 'element(s)');

    return { classes: generatedClasses, results: results };
  }

  /**
   * Generate tools.css content from extracted styles.
   * @returns {string} CSS file content
   */
  function generateCSS() {
    if (Object.keys(generatedClasses).length === 0) {
      extract(); // Auto-extract if not done yet
    }

    var lines = [
      '/**',
      ' * tools.css — Auto-generated utility classes from inline styles',
      ' * Generated by CortexFreelancer.styleExtractor',
      ' * Date: ' + new Date().toISOString(),
      ' *',
      ' * Replace inline style="..." attributes with these classes.',
      ' * Review and rename classes to match your naming convention.',
      ' */',
      ''
    ];

    for (var cls in generatedClasses) {
      if (generatedClasses.hasOwnProperty(cls)) {
        lines.push(generatedClasses[cls]);
        lines.push('');
      }
    }

    // Add common utility classes
    lines.push('/* ── Common Utility Classes ─────────────────────────── */');
    lines.push('');
    lines.push('.cf-hidden { display: none; }');
    lines.push('.cf-visible { display: block; }');
    lines.push('.cf-flex { display: flex; }');
    lines.push('.cf-flex-center { display: flex; align-items: center; justify-content: center; }');
    lines.push('.cf-text-center { text-align: center; }');
    lines.push('.cf-text-left { text-align: left; }');
    lines.push('.cf-text-right { text-align: right; }');
    lines.push('.cf-bold { font-weight: bold; }');
    lines.push('.cf-italic { font-style: italic; }');
    lines.push('.cf-mt-1 { margin-top: 0.5rem; }');
    lines.push('.cf-mt-2 { margin-top: 1rem; }');
    lines.push('.cf-mt-3 { margin-top: 1.5rem; }');
    lines.push('.cf-mb-1 { margin-bottom: 0.5rem; }');
    lines.push('.cf-mb-2 { margin-bottom: 1rem; }');
    lines.push('.cf-p-1 { padding: 0.5rem; }');
    lines.push('.cf-p-2 { padding: 1rem; }');
    lines.push('.cf-p-3 { padding: 1.5rem; }');
    lines.push('.cf-w-full { width: 100%; }');
    lines.push('.cf-rounded { border-radius: 0.5rem; }');
    lines.push('.cf-shadow { box-shadow: 0 2px 8px rgba(0,0,0,0.1); }');
    lines.push('.cf-truncate { overflow: hidden; text-overflow: ellipsis; white-space: nowrap; }');
    lines.push('');

    var css = lines.join('\n');

    console.log('[StyleExtractor] Generated tools.css (' + css.length + ' bytes)');
    console.log('[StyleExtractor] Copy the output or call generateCSS() to get the string');

    return css;
  }

  /**
   * Apply: replace inline styles with generated classes.
   * @param {Object} [options]
   * @param {boolean} [options.removeInline=true]  Remove inline style after adding class
   * @param {boolean} [options.dryRun=false]
   */
  function apply(options) {
    options = options || {};
    var removeInline = options.removeInline !== false;
    var dryRun = options.dryRun === true;

    if (lastResults.length === 0 || Object.keys(generatedClasses).length === 0) {
      extract();
    }

    var applied = 0;
    for (var i = 0; i < lastResults.length; i++) {
      var entry = lastResults[i];
      if (!entry.suggestedClass) continue;
      if (dryRun) continue;

      entry.element.classList.add(entry.suggestedClass);
      if (removeInline) {
        entry.element.removeAttribute('style');
      }
      applied++;
    }

    // Inject generated CSS into page
    if (!dryRun && applied > 0) {
      var styleEl = document.createElement('style');
      styleEl.id = 'cf-extracted-styles';
      styleEl.textContent = Object.keys(generatedClasses)
        .map(function (k) { return generatedClasses[k]; })
        .join('\n');
      document.head.appendChild(styleEl);
    }

    console.log('[StyleExtractor]', dryRun ? 'Would apply' : 'Applied',
      applied, 'class(es)');

    return { applied: applied, total: lastResults.length };
  }

  /**
   * Print a report of found inline styles.
   */
  function report() {
    if (lastResults.length === 0) {
      scan();
    }
    console.group('[StyleExtractor] Inline Style Report (' + lastResults.length + ' found)');
    console.table(lastResults.map(function (r) {
      return {
        Element: r.description,
        Style: r.inlineStyle.substring(0, 80),
        'Suggested Class': r.suggestedClass || '(run extract())'
      };
    }));
    console.groupEnd();
    return lastResults;
  }

  // ── Export ────────────────────────────────────────────────────────────

  window.CortexFreelancer.styleExtractor = {
    scan: scan,
    extract: extract,
    generateCSS: generateCSS,
    apply: apply,
    report: report
  };

  console.log('[CF] Style extractor loaded');
})();
